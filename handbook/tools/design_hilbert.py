# design_hilbert.py - generator for the 31-tap Hilbert FIR of Handbook Chapter 6 (listing "hilbert_coeffs").
# The listing says "generate with scipy.signal.remez(..., type='hilbert')".
# This script is that step: equiripple design over 0.05..0.45 of fs (symmetric about fs/4, which is what makes every
# odd-indexed tap come out zero), then it forces the structure the listing relies on EXACTLY:
#   h[i] == -h[30-i]  (antisymmetric)   and   h[odd] == 0.0f  (incl. the centre tap h[15]).
# remez returns the odd taps as ~1e-15 (round-off); the script asserts they are that small before zeroing them.
# Usage:  python3 design_hilbert.py [out.h]      (default: hilbert_coeffs.h in the current directory)
import sys
import numpy as np
import scipy.signal as sig

N = 31
h = sig.remez(N, [0.05, 0.45], [1], type='hilbert', fs=1.0)
assert np.max(np.abs(h[1::2])) < 1e-9, "odd taps are not ~0: band edges are not symmetric about fs/4"
h = (h - h[::-1]) / 2.0          # exact antisymmetry
h[1::2] = 0.0                    # exact structural zeros (odd indices, centre tap included)
h = h.astype(np.float32)         # the listing stores float
assert np.all(h == -h[::-1]) and np.all(h[1::2] == 0.0)

out = sys.argv[1] if len(sys.argv) > 1 else "hilbert_coeffs.h"
with open(out, "w") as f:
    f.write("/* Generated by tools/design_hilbert.py (scipy.signal.remez, type='hilbert', 31 taps, band 0.05..0.45 fs). */\n")
    f.write("#ifndef HB_HILBERT_COEFFS_H\n#define HB_HILBERT_COEFFS_H\n")
    f.write("#define HB_HILBERT_COEFFS_INIT \\\n    ")
    f.write(", ".join(("%.9ef" % v) if v != 0.0 else "0.0f" for v in h))
    f.write("\n#endif\n")
