#!/usr/bin/env python3
"""gen_farrow_weights.py -- generates the Q15 Lagrange weight table that Chapter 11 describes as produced offline.

Writes include/generated/farrow_weights.h: the Q15 table `farrow_weights_q15[FARROW_MU_STEPS][4]` that the Handbook's
timing_interpolate_farrow_cubic_q15() declares `extern`.

Row `step` holds { p_m1, p_0, p_1, p_2 } for mu = step / FARROW_MU_STEPS, from the SAME four-point Lagrange formulas
timing_interpolate_farrow_cubic() uses:
    p_m1 = -mu (mu-1)(mu-2)/6      p_0 = (mu+1)(mu-1)(mu-2)/2
    p_1  = -(mu+1) mu (mu-2)/2     p_2 = (mu+1) mu (mu-1)/6
Rounding is to nearest; the only value that does not fit int16 Q15 is p_0(mu=0) = 1.0 (= 32768), which saturates to 32767
(a one-LSB DC gain error at step 0, noted in the Chapter 11 listing).
Usage:  python3 tools/gen_farrow_weights.py [steps] > include/generated/farrow_weights.h   (default steps = 32)
"""
import sys
steps = int(sys.argv[1]) if len(sys.argv) > 1 else 32
def weights(mu):
    return (-mu*(mu-1)*(mu-2)/6.0, (mu+1)*(mu-1)*(mu-2)/2.0, -(mu+1)*mu*(mu-2)/2.0, (mu+1)*mu*(mu-1)/6.0)
def q15(v):
    r = int(round(v * 32768.0))          # python round(): half-to-even, irrelevant here (no exact .5 values except 0.5*k/32768)
    return max(-32768, min(32767, r))
print("/* GENERATED by tools/gen_farrow_weights.py (steps=%d) -- do not edit. */" % steps)
print("#ifndef HB_GENERATED_FARROW_WEIGHTS_H\n#define HB_GENERATED_FARROW_WEIGHTS_H\n")
print("#if FARROW_MU_STEPS != %d\n#error \"farrow_weights.h was generated for %d steps\"\n#endif\n" % (steps, steps))
print("const int16_t farrow_weights_q15[FARROW_MU_STEPS][4] = {")
for s in range(steps):
    w = [q15(v) for v in weights(s / steps)]
    print("    { %6d, %6d, %6d, %6d }%s   /* mu = %2d/%d */" % (*w, "," if s < steps-1 else "", s, steps))
print("};\n\n#endif")
