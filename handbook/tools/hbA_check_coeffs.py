#!/usr/bin/env python3
"""Regenerate include/generated/coeffs.h with tools/design_filter.py (HB[20]) in a scratch dir and compare it with
(a) the committed header, byte for byte, and (b) the coefficient list given in HB[21].
Needs numpy and scipy.  Usage:  python3 tools/hbA_check_coeffs.py   (from the handbook/ directory or anywhere)."""
import os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BOOK_HB21 = [-212, 5, 560, 678, -474, -1977, -1180, 3418, 9498,
             12339, 9498, 3418, -1180, -1977, -474, 678, 560, 5, -212]   # the list in HB[21]

with tempfile.TemporaryDirectory() as d:
    subprocess.check_call([sys.executable, '-I', os.path.join(HERE, 'design_filter.py')], cwd=d)
    gen = open(os.path.join(d, 'coeffs.h')).read()
committed = open(os.path.join(ROOT, 'include', 'generated', 'coeffs.h')).read()
vals = [int(v) for v in re.findall(r'-?\d+', gen.split('=')[1])]
ok = True
if gen != committed:
    print('MISMATCH: regenerated coeffs.h differs from include/generated/coeffs.h'); ok = False
if vals != BOOK_HB21:
    print('MISMATCH: regenerated values differ from HB[21]:', vals); ok = False
if f'#define FIR_TAPS {len(BOOK_HB21)}' not in gen:
    print('MISMATCH: FIR_TAPS'); ok = False
if ok:
    print('coeffs.h regenerated by design_filter.py matches the committed header byte for byte and the 19 values listed in HB[21]')
sys.exit(0 if ok else 1)
