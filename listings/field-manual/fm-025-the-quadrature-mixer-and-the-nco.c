#define NCO_TABLE_SIZE 256
static const int16_t cos_table[256] = { /* generated by design_nco_table.py above - not hand-typed */ };
static const int16_t sin_table[256] = { /* generated by design_nco_table.py above - not hand-typed */ };

typedef struct {
    uint32_t phase_acc;   // full circle = 2^32 exactly (Costas's math below relies on this)
    uint32_t phase_inc;   // current per-sample phase step, base_inc + any active correction
    uint32_t base_inc;    // the free-running step for the nominal carrier, set once at init
} nco_t;

// phase_inc for a desired carrier frequency fc at sample rate fs:
uint32_t nco_phase_inc_for_freq(float fc, float fs) {
    return (uint32_t)((fc / fs) * 4294967296.0);   // 2^32
}

// Quadrature-mix one real sample into I/Q (before the lowpass filter that follows).
// sample and the table are both Q15, so i_out/q_out land in Q30, NOT Q15 - mixer_to_q15()
// below shifts that back down before anything downstream (a Q15 FIR, in particular) touches it.
static inline void quadrature_mix(nco_t *nco, int16_t sample, int32_t *i_out, int32_t *q_out) {
    uint8_t idx = (uint8_t)(nco->phase_acc >> 24);   // top 8 bits index the table
    *i_out = (int32_t)sample * cos_table[idx];        // Q15 x Q15 -> Q30
    *q_out = -(int32_t)sample * sin_table[idx];
    nco->phase_acc += nco->phase_inc;                 // wraps naturally in uint32_t
}

// Q30 mixer product -> Q15, rounded (same discipline as q2_14_mul_round in Chapter 2) and
// saturated: the product's magnitude can land fractionally above INT16_MAX at the table's
// extreme entries. Truncating instead, or - worse - narrowing the raw Q30 value straight to
// int16_t with a bare cast, keeps only its low 16 bits: noise, not a scaled-down sample.
static inline int16_t mixer_to_q15(int32_t wide_q30) {
    int32_t v = (wide_q30 + (1 << 14)) >> 15;
    if (v > 32767) v = 32767;
    if (v < -32768) v = -32768;
    return (int16_t)v;
}
