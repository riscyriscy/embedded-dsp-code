// Practical Hilbert-transformer FIR: 31 taps (odd length -> exact integer group
// delay), designed offline the same way Chapter 2's FIR coefficients are (equiripple
// design targeting a -90-degree phase shift over the passband of interest, not a
// magnitude response), then exported as a constant array - never hand-typed.
// Every ODD-indexed tap below is exactly 0 by construction (including the center
// tap, h[15], since HILBERT_TAPS is odd); the even-indexed taps carry the real,
// antisymmetric coefficient values - correcting the direction of the earlier
// bullet's own point, worth restating precisely here since the code below relies
// on it to skip exactly the right half of the taps.
#define HILBERT_TAPS 31
#define HILBERT_DELAY ((HILBERT_TAPS - 1) / 2)   // 15 samples: exact integer group delay

static const float hilbert_coeffs[HILBERT_TAPS] = {
    /* h[0..30], odd indices exactly 0.0f (including h[15]), even indices nonzero
       and antisymmetric about the center tap (h[i] == -h[30 - i]); generate with
       scipy.signal.remez(..., type='hilbert') or equivalent, exported the same
       way as any other FIR here */
};

typedef struct {
    // One history buffer serves BOTH outputs: the Q path convolves it against
    // hilbert_coeffs below, and the I path just reads it back HILBERT_DELAY
    // samples old, no second delay line needed since delay_line already holds
    // more history (HILBERT_TAPS samples) than the I path's delay requires.
    float delay_line[HILBERT_TAPS];
    int idx;
} hilbert_iq_t;

// Produces one I/Q pair per input sample, correct from the first call onward for
// I (a pure delay) and settling in over the first HILBERT_TAPS samples for Q (the
// FIR's own fill time), same as any other freshly-started FIR/CIC stage in this
// book. Q is the negated FIR output - the sign that makes instantaneous frequency
// come out positive for a positive input frequency, verified numerically against
// a reference analytic-signal implementation before relying on it, the same way
// any sign convention in this book is checked rather than assumed.
void hilbert_iq_process(hilbert_iq_t *h, float x, float *i_out, float *q_out) {
    h->delay_line[h->idx] = x;

    // Q: convolve against hilbert_coeffs, stepping by 2 to touch only the
    // nonzero even-indexed taps; hist_idx walks the same "age i" convention
    // fir_process() uses above, just computed directly instead of via a
    // step-by-step ternary walk, since i itself steps by 2 here, not 1.
    float q_fir = 0.0f;
    for (int i = 0; i < HILBERT_TAPS; i += 2) {
        int hist_idx = h->idx - i;
        if (hist_idx < 0) hist_idx += HILBERT_TAPS;
        q_fir += hilbert_coeffs[i] * h->delay_line[hist_idx];
    }
    *q_out = -q_fir;

    // I: x(t) delayed by exactly HILBERT_DELAY samples, read straight out of
    // the same delay_line the Q path just used - no separate buffer needed.
    int i_idx = h->idx - HILBERT_DELAY;
    if (i_idx < 0) i_idx += HILBERT_TAPS;
    *i_out = h->delay_line[i_idx];

    h->idx = (h->idx + 1) % HILBERT_TAPS;
}
